def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def render() -> str:
    lines = [
        "# Provenance of the vendored test vectors",
        "",
        "This file is generated by `scripts/vectors.py`. Do not edit it by hand.",
        "A test reads these files from disk and fetches nothing (Part 14 rule",
        "`IMP-036`). To refresh a corpus, pin the new commit in the script, replace",
        "the files, and run the script again.",
        "",
    ]
    for c in CORPORA:
        base = VECTORS / c["dir"]
        lines += [
            f"## `{c['dir']}/` — {c['name']}",
            "",
            f"- Upstream: {c['repo']}, path `{c['path']}`",
            f"- Commit: `{c['commit']}` ({c['date']})",
            f"- License: {c['license']}",
            f"- Note: {c['note']}",
            "",
            "| File | Bytes | SHA-256 |",
            "| --- | --- | --- |",
        ]
        # A Windows path sorts without case, and a POSIX path sorts with it.
        for p in sorted(base.rglob("*"), key=lambda p: p.relative_to(VECTORS).as_posix()):
            if p.is_file():
                rel = p.relative_to(VECTORS).as_posix()
                lines.append(f"| `{rel}` | {p.stat().st_size} | `{sha256(p)}` |")
        lines.append("")
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    text = render()
    path = VECTORS / "PROVENANCE.md"

    if "--check" in argv:
        current = path.read_text(encoding="utf-8") if path.exists() else ""
        if current != text:
            print("PROVENANCE.md is stale; run scripts/vectors.py")
            return 1
        print("PROVENANCE.md is current")
        return 0

    path.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {path.relative_to(ROOT).as_posix()}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
