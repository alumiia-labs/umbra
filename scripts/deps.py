#!/usr/bin/env python3
"""Generate DEPENDENCIES.md from the resolved dependency graph.

Part 15 §15.2.4 rules IMP-010 and IMP-011 require this file, generated by a
script and never edited by hand. It holds, for each target triple, the crate
count of each register, the crate list with versions, the cap and the PASS or
FAIL result, the commit and date of the measurement, and the toolchain.

Register membership is read from deny.toml: the [bans] allow list carries a
comment `# R1`, `# R2`, or `# build` on each entry. A crate outside the lists
charges R3. The linked graph is `cargo tree -e normal,no-proc-macro`; a
proc-macro, a build script, and a crate that only those reach form the build
register, which no binary links and which carries no cap (Part 15 §15.2.3).
No R3 cap exists in v1 either, thus R3 and build report a count only.

Usage: python scripts/deps.py [--check]
  --check   exit 1 when the generated text differs from the committed file.
"""
from __future__ import annotations

import datetime as dt
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TARGETS = [
    "aarch64-linux-android",
    "x86_64-unknown-linux-gnu",
    "wasm32-unknown-unknown",
]
CAPS = {"R1": 40, "R2": 30}
WORKSPACE = {"umbra-crypto"}


def run(*args: str) -> str:
    return subprocess.run(args, cwd=ROOT, check=True, capture_output=True, text=True).stdout


def registers() -> dict[str, str]:
    """crate name -> register, from the allow list of deny.toml."""
    text = (ROOT / "deny.toml").read_text(encoding="utf-8")
    out = {}
    for m in re.finditer(r'\{\s*crate\s*=\s*"([^"@]+)[^}]*\}\s*,?\s*#\s*(R[12]|build)', text):
        out[m.group(1)] = m.group(2)
    return out


def graph(target: str, edges: str) -> dict[str, str]:
    """crate name -> version for one target over the named edge kinds."""
    out = run("cargo", "tree", "--target", target, "-e", edges, "--prefix", "none",
              "--format", "{p}")
    crates = {}
    for line in out.splitlines():
        line = line.strip()
        if not line or line.endswith("(*)"):
            continue
        m = re.match(r"^(\S+) v(\S+)", line)
        if not m or m.group(1) in WORKSPACE:
            continue
        crates[m.group(1)] = m.group(2)
    return crates


def render() -> str:
    reg = registers()
    commit = run("git", "rev-parse", "--short", "HEAD").strip()
    rustc = run("rustc", "--version").strip()
    cargo = run("cargo", "--version").strip()
    today = dt.date.today().isoformat()
    lines = [
        "# Dependencies",
        "",
        "This file is generated by `scripts/deps.py`. Do not edit it by hand.",
        "Part 15 §15.2 gives the three registers and their caps.",
        "",
        f"- Commit: `{commit}`",
        f"- Date: {today}",
        f"- Toolchain: `{rustc}`, `{cargo}`",
        "",
    ]
    for target in TARGETS:
        linked = graph(target, "normal,no-proc-macro")
        full = graph(target, "normal,build")
        by_reg: dict[str, list[tuple[str, str]]] = {"R1": [], "R2": [], "R3": [], "build": []}
        for name, ver in sorted(full.items()):
            if name not in linked:
                by_reg["build"].append((name, ver))
                continue
            r = reg.get(name, "R3")
            if r == "build":
                r = "R3"  # a crate tagged build that the linked graph reaches is misfiled
            by_reg[r].append((name, ver))
        lines += [f"## `{target}`", ""]
        lines += ["| Register | Count | Cap | Result |", "| --- | --- | --- | --- |"]
        for r in ("R1", "R2", "R3", "build"):
            n = len(by_reg[r])
            cap = CAPS.get(r)
            result = "n/a" if cap is None else ("PASS" if n <= cap else "FAIL")
            lines.append(f"| {r} | {n} | {cap if cap is not None else 'none'} | {result} |")
        lines.append("")
        for r in ("R1", "R2", "R3", "build"):
            if not by_reg[r]:
                continue
            lines.append(f"### {r}")
            lines.append("")
            lines += [f"- `{name}` {ver}" for name, ver in by_reg[r]]
            lines.append("")
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    text = render()
    path = ROOT / "DEPENDENCIES.md"
    if "--check" in argv:
        current = path.read_text(encoding="utf-8") if path.exists() else ""
        # the date and the commit change at each commit; compare the rest
        strip = lambda s: re.sub(r"^- (Date|Commit): .*$", "", s, flags=re.M)
        if strip(current) != strip(text):
            print("DEPENDENCIES.md is stale; run scripts/deps.py")
            return 1
        print("DEPENDENCIES.md is current")
        return 0
    path.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {path.name}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
